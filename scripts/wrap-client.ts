/**
 * Wrap the built browser entry in the module-loader call the Harness shell
 * expects.
 *
 * tsdown emits a CommonJS module; the shell's module table registers a factory
 * that receives `require` and returns the plugin's exports. This script turns
 * one into the other, exactly like the shipped client bundles, and removes the
 * intermediate artifact.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

interface PackageJson {
  name: string
  version: string
}

const root: string = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageJson: PackageJson = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')) as PackageJson
const candidates: string[] = ['lib/.client/client.cjs', 'lib/.client/client.js']
const source: string | undefined = candidates.map((path) => resolve(root, path)).find((path) => existsSync(path))
if (source === undefined) {
  throw new Error(`wrap-client: no browser bundle found (looked for ${candidates.join(', ')})`)
}

const code: string = readFileSync(source, 'utf8')
const indented: string = code
  .split('\n')
  .map((line) => (line === '' ? line : `      ${line}`))
  .join('\n')

const wrapped: string = `/* ${packageJson.name} ${packageJson.version} — generated by tsdown; do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageJson.name)},
  factory: (require) => {
    const module = { exports: {} };
    (function (module, exports, require) {
${indented}
    })(module, module.exports, require);
    return module.exports;
  },
});
`

const target: string = resolve(root, 'lib/client.js')
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, wrapped)
rmSync(resolve(root, 'lib/.client'), { recursive: true, force: true })
console.log(`wrap-client: ${target} (${Buffer.byteLength(wrapped)} bytes)`)
